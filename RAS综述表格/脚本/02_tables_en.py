#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""英文版表1–3：出表1，核表2、表3（make 时出表，make check 时 --check）。

表1：与中文版同源——药物集合、阶段、试验计数取自图9 的 `图八_药物泳道.csv`，
     英文文字取自 `数据/表一_补充列_en.tsv`；写 `英文版/Table1_RAS-directed_drug_landscape.md`。
表2、表3：英文版是人工翻译件（`英文版/Table2_*.md`、`Table3_*.md`），不由脚本生成。

核对（任何一条不过即非零退出）：
  1. 英文补充列与中文补充列、图9 三方的药物集合一致，节号列逐药相同；
  2. 表1 逐药：中文补充列每个字段里的每个数，英文同字段里都要出现（按多重集合，
     英文可以多：「Ⅱ期」译成 phase 2 会多出一个 2）；
  3. 表2、表3 逐行：表格行（以 | 开头、非分隔行）数目相同，中文行里的每个数，
     英文对应行里都要出现。附注是意译（去掉了项目内部的流程记录），不逐数核。
中文表改了而英文没跟上，这里就会报出来。

用法：python3 脚本/02_tables_en.py [--check]
"""
import collections, csv, glob, io, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LANES = os.path.join(os.path.dirname(ROOT), 'RAS综述示意图', '数据', '图八_药物泳道.csv')
ZH = os.path.join(ROOT, '数据', '表一_补充列.tsv')
EN = os.path.join(ROOT, '数据', '表一_补充列_en.tsv')
ENDIR = os.path.join(ROOT, '英文版')
OUT = os.path.join(ENDIR, 'Table1_RAS-directed_drug_landscape.md')
PAIRS = [('表二_获批药物与适应证、监管路径.md', 'Table2_approved_drugs_indications_regulatory_routes.md'),
         ('表三_关键临床研究汇总表.md', 'Table3_key_clinical_studies.md')]

SNAP = '2026-10-20'
LANE_NAME = {
    '1': 'OFF-state covalent inhibitors',
    '2': 'Non-covalent / reversible inhibitors (non-cysteine alleles)',
    '3': 'RAS(ON) tri-complex inhibitors',
    '4': 'Degraders and other direct modalities',
    '5': 'Upstream nodes and immune strategies',
    '6': 'Downstream pathway combination (does not bind RAS directly)',
}
STAGE_EN = {'Preclinical': 'Preclinical', 'Phase 1': 'Phase 1', 'Phase 1/2': 'Phase 1/2',
            'Phase 2': 'Phase 2', 'Phase 3': 'Phase 3', 'Approved': 'Approved'}
ORDER = ['Preclinical', 'Phase 1', 'Phase 1/2', 'Phase 2', 'Phase 3', 'Approved']
NUM = re.compile(r'\d+(?:\.\d+)?')
GENE = re.compile(r'(?<![*\w])(KRAS|NRAS|HRAS|RAS)(?![*\w])')


def nums(s):
    return collections.Counter(NUM.findall(s.replace('·', '.')))


def missing(zh, en):
    """中文里有、英文里不够数的数（多重集合差）。"""
    return sorted((nums(zh) - nums(en)).elements())


def tsv(p):
    return {r['drug']: r for r in csv.DictReader(io.open(p, encoding='utf-8'), delimiter='\t')}


def table_rows(p):
    out = []
    for line in io.open(p, encoding='utf-8'):
        s = line.strip()
        if s.startswith('|') and not re.match(r'^\|[\s|:-]+\|$', s):
            out.append(s)
    return out


def check():
    bad = []
    lanes = {r['drug'] for r in csv.DictReader(io.open(LANES, encoding='utf-8'))}
    zh, en = tsv(ZH), tsv(EN)
    for name, s in (('中文补充列', set(zh)), ('英文补充列', set(en))):
        if s != lanes:
            bad.append('%s ↔ 图9 药物集合不一致：只在图9 %s；只在%s %s'
                       % (name, sorted(lanes - s), name, sorted(s - lanes)))
    for d in sorted(set(zh) & set(en)):
        if zh[d]['section'] != en[d]['section']:
            bad.append('表1 %s：节号 %s ≠ %s' % (d, zh[d]['section'], en[d]['section']))
        for col in ('gene', 'alleles', 'state', 'mechanism', 'result'):
            m = missing(zh[d][col], en[d][col])
            if m:
                bad.append('表1 %s [%s]：英文缺 %s' % (d, col, ' '.join(m)))
    for zp, ep in PAIRS:
        zr, er = table_rows(os.path.join(ROOT, zp)), table_rows(os.path.join(ENDIR, ep))
        if len(zr) != len(er):
            bad.append('%s：表格行数 %d ≠ 英文 %d' % (zp, len(zr), len(er)))
            continue
        for i, (a, b) in enumerate(zip(zr, er), 1):
            m = missing(a, b)
            if m:
                bad.append('%s 第 %d 行（%s）：英文缺 %s' % (zp, i, b.split('|')[1].strip()[:40], ' '.join(m)))
    return bad


def build():
    lanes = list(csv.DictReader(io.open(LANES, encoding='utf-8')))
    en = tsv(EN)
    rows = sorted(lanes, key=lambda r: (int(r['lane']), -ORDER.index(r['stage']), r['drug'].lower()))
    o = io.StringIO()
    o.write('# Table 1　Landscape of RAS-directed drugs\n\n')
    o.write('> English version of `表一_药物全景表.md`, generated by `脚本/02_tables_en.py` — do not edit by hand. '
            'Placed at the end of §4.7. Wide table; set in landscape where needed.\n>\n')
    o.write('> The drug set, highest phase and trial counts come from the Figure 9 data file '
            '(`RAS综述示意图/数据/图八_药物泳道.csv`), the same source as the Chinese table; the English text of the '
            'other columns is in `数据/表一_补充列_en.tsv`.\n>\n')
    o.write('> "Registered trials" is the number of trials registering the drug in this review\'s ClinicalTrials.gov '
            'corpus (REST API v2, snapshot of %s; 1 133 RAS-related phase 1–3 interventional oncology trials). It '
            'measures development activity, not efficacy; trials in which the drug appears only as a combination '
            'component are counted, so counts overlap. "Highest phase" is the highest phase the drug reached in that '
            'corpus.\n>\n' % SNAP)
    o.write('> Every value in the "Representative studies and key results" column can be found, with its citation, '
            'in the section given; **single-arm response rates are always given with sample size and assessment '
            'method**. Where the text gives no readout, the table says so and adds nothing from outside the text. '
            'Approval information is in Table 2 and must be re-checked against current labels at the proof stage.\n\n')
    cur = None
    for r in rows:
        if r['lane'] != cur:
            cur = r['lane']
            o.write('\n## Lane %s　%s\n\n' % (cur, LANE_NAME[cur]))
            o.write('| Drug (code) | Target | Alleles covered | Conformational state | Mechanism | Highest phase | '
                    'Registered trials | Representative studies and key results | Section |\n')
            o.write('|---|---|---|---|---|---|---|---|---|\n')
        e = en[r['drug']]
        code = ' / '.join(p.strip() for p in re.split(r'[;；]', r['code']) if p.strip())
        name = r['drug'] + (' (%s)' % code if code else '')
        it = lambda s: GENE.sub(r'*\1*', s)
        o.write('| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n' % (
            name, it(e['gene']), it(e['alleles']), e['state'], it(e['mechanism']),
            STAGE_EN[r['stage']], r['n_trials'], e['result'], e['section']))
    o.write('\n> Abbreviations: CRC / mCRC, (metastatic) colorectal cancer; DCR, disease control rate; IRRC, independent '
            'radiology review committee; LGSOC, low-grade serous ovarian cancer; MTD, maximum tolerated dose; NSCLC, '
            'non-small-cell lung cancer; ORR, objective response rate; OS, overall survival; PFS, progression-free '
            'survival; TCR, T-cell receptor; TRAE, treatment-related adverse event; VAF, variant allele frequency.\n')
    o.write('\n---\n\n## Notes to Table 1\n\n')
    o.write('**1. This table has the same drug set as Figure 9, and therefore the same boundaries.** The coordinate '
            'system covers only **drugs acting on the RAS protein**, together with its upstream processing and '
            'regulatory nodes and immune strategies against mutant-RAS neoantigens. Gene therapies (siRNA / miRNA / '
            'CRISPR) target the gene and its transcripts rather than the RAS protein and have no conformational state, '
            'so they are outside the coordinates (see §4.7, paragraph 1d). The one exception is iExosome siG12D, which '
            'has human data discussed in §5.3, paragraph 6a; it is listed as an "RNA therapy" with "not applicable" '
            'in the conformational-state column.\n\n')
    o.write('**2. Drugs mentioned in the text but not in this table, and why.**\n\n')
    o.write('| Drug | Where mentioned | Reason for exclusion |\n|---|---|---|\n')
    o.write('| ifebemtinib | §6.5, paragraph 4e; Figure 12 (with garsorasib, first-line confirmed ORR 82%) | A FAK '
            'inhibitor that neither acts on the RAS protein nor belongs to the upstream input nodes or immune '
            'strategies; it is a combination partner, not a RAS-directed drug. |\n')
    o.write('| cetuximab, panitumumab | §5.2; §6.5, paragraph 2 | Anti-EGFR antibodies; as above, combination '
            'partners. |\n')
    o.write('| carboplatin, pemetrexed, gemcitabine, nab-paclitaxel, docetaxel | §5.1, §5.3; §6.5, paragraph 5 | '
            'Cytotoxic drugs, used as comparators or combination partners. |\n')
    o.write('| avutometinib, defactinib, binimetinib, selumetinib, trametinib, CI-1040 | §4.1, §5.4 | Downstream '
            'kinase inhibitors and a RAF/MEK molecular glue acting below RAS, outside the coordinates; they appear in '
            '§4.1 as evidence from the era of indirect strategies. **Exception**: avutometinib + defactinib is included '
            '(lane 6) for the reason in note 5 — not because it acts on RAS, but because its indication is defined '
            'by *KRAS* mutation and it is approved. |\n')
    o.write('\n**3. A count to verify at the proof stage.** The number of drugs in Figure 9 and in this table is '
            '**computed by the script** and is currently **%d**; the identity and source of each drug added during '
            'revision are recorded in `RAS综述示意图/数据/图八_直接RAS候选.tsv`. **Wherever the text states this number, '
            're-check it after any change to the drug set.**\n' % len(lanes))
    o.write('\n**4. The identity of sitneprotafib.** It is **JAB-3312**, not a different molecule. Two independent '
            'sources agree: Hendriks et al. 2026 (*Lancet Respir Med*, review) writes "plus the SHP2 inhibitor '
            'sitneprotafib (JAB-3312), objective"; the manufacturer\'s public information and ClinicalTrials.gov '
            'registration NCT05288205 (phase 1/2a of the glecirasib combination, first-line ORR 71%) refer to the '
            'same molecule, and that registration is one of the 5 trials attributed to JAB-3312 in this review\'s '
            'corpus. **Names follow those published by the manufacturer / FDA**: Jacobio\'s own announcement writes '
            '"Sitneprotafib (JAB-3312)".\n')
    o.write('\n**5. Avutometinib + defactinib in lane 6 is included by indication, not by mechanism.** Avutometinib is '
            'a RAF/MEK molecular glue (clamp) and defactinib a FAK inhibitor; **neither binds RAS directly**, and they '
            'act downstream of and parallel to RAS — so the combination has **its own lane 6 (downstream pathway '
            'combination)** rather than lane 5 (upstream nodes and immune strategies). It is in this table because '
            'the FDA accelerated approval of 2025-05-08 defines its indication by *KRAS* mutation (*KRAS*-mutated '
            'recurrent LGSOC; see Table 2, note 9). The row label in Figure 9 names the targets in parentheses and '
            'the figure legend explains this.\n')
    os.makedirs(ENDIR, exist_ok=True)
    io.open(OUT, 'w', encoding='utf-8').write(o.getvalue())
    print('已写 英文版/%s：%d 药' % (os.path.basename(OUT), len(rows)))


if __name__ == '__main__':
    if '--check' not in sys.argv[1:]:
        build()
    bad = check()
    for b in bad:
        print('✗ ' + b)
    print('英文版表1–3 ↔ 中文版：不一致 %d 处' % len(bad))
    sys.exit(1 if bad else 0)
