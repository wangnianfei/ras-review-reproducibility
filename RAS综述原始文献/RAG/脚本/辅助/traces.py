# 源文件写法的条目（标「专著」）也适用于复现包：两者剥的都是未经投稿改写的源文本
_ALIAS = {'复现包': '专著'}


def trace_rules(exit_):
    exit_ = _ALIAS.get(exit_, exit_)
    return tuple(e[:2] for e in TRACE if len(e) < 3 or e[2] == exit_)


def strip_traces(doc, exit_='专著'):
    """按 TRACE 剥内部痕迹；返回 (新文本, 落空的条目)。"""
    miss = []
    for a, b in trace_rules(exit_):
        if a.startswith('re:'):
            if not re.search(a[3:], doc):
                miss.append(a)
            doc = re.sub(a[3:], b, doc)
            continue
        if a not in doc:
            miss.append(a)
        doc = doc.replace(a, b)
    return doc, miss


def main(paths):
    rules = trace_rules('复现包')
    for p in paths:
        t = io.open(p, encoding='utf-8').read()
        new, miss = strip_traces(t, '复现包')
        if new != t:
            io.open(p, 'w', encoding='utf-8').write(new)
        print('  剥内部痕迹 %2d 条  %s' % (len(rules) - len(miss), p))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
